function packageDirectory(packagePath) {
  return join(root, "node_modules", ...packagePath.split("/"));
}

function makeWoff2Only(css, sourceFamily, publicFamily) {
  return css
    .replaceAll(`font-family: '${sourceFamily}'`, `font-family: '${publicFamily}'`)
    .replace(/, url\([^)]*\.woff\) format\('woff'\)/g, "")
    .replaceAll("url(./files/", "url(./");
}

function referencedWoff2Files(css) {
  return [...css.matchAll(/url\((?:['"])?\.\/([^'")]+\.woff2)(?:['"])?\)/g)].map(
    (match) => match[1],
  );
}

mkdirSync(outputRoot, { recursive: true });

// Font directories are generated artifacts. Remove them before writing so an
// obsolete accepted-demo family can never remain silently available.
for (const entry of readdirSync(outputRoot, { withFileTypes: true })) {
  if (entry.isDirectory()) rmSync(join(outputRoot, entry.name), { recursive: true, force: true });
}

for (const family of fontsourceFamilies) {
  const packageRoot = packageDirectory(family.packagePath);
  const familyOutput = join(outputRoot, family.slug);
  mkdirSync(familyOutput, { recursive: true });

  const css = family.cssFiles
    .map((file) => readFileSync(join(packageRoot, file), "utf8"))
    .map((source) => makeWoff2Only(source, family.sourceFamily, family.publicFamily))
    .join("\n");

  const assetFiles = [...new Set(referencedWoff2Files(css))];
  for (const file of assetFiles) {
    copyFileSync(join(packageRoot, "files", file), join(familyOutput, basename(file)));
  }

  copyFileSync(join(packageRoot, "LICENSE"), join(familyOutput, "OFL-1.1.txt"));
  writeFileSync(join(familyOutput, "font.css"), css);
  cachedAssets.push(
    `${family.slug}/font.css`,
    ...assetFiles.map((file) => `${family.slug}/${basename(file)}`),
  );
  console.log(`${family.slug}: ${assetFiles.length} WOFF2 files`);
}

